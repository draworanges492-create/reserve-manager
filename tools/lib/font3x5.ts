/** Returns 5 rows of 3 booleans, or null for unsupported characters. */
export function glyph(char: string): boolean[][] | null {
  const rows = GLYPHS[char.toUpperCase()];
  return rows ? rows.map((row) => [...row].map((c) => c === '#')) : null;
}
